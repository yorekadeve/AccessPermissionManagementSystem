    private void addPermissionButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addPermissionButtonActionPerformed
        // TODO add your handling code here:
        
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "CREATE",
        "Permissions")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to create permissions."
    );

    return;
}
        
        AddPermissionForm addPermissionForm =
        new AddPermissionForm(loggedInAccount);

        addPermissionForm.setVisible(true);

        this.dispose();
    }//GEN-LAST:event_addPermissionButtonActionPerformed

    private void updatePermissionButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updatePermissionButtonActionPerformed
        // TODO add your handling code here:
        
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "UPDATE",
        "Permissions")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to update permissions."
    );

    return;
}
        
        int selectedRow = permissionsTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a permission to update."
    );

    return;
}

int permissionId =
        Integer.parseInt(
                permissionsTable.getValueAt(
                        selectedRow, 0
                ).toString()
        );

int operationId =
        Integer.parseInt(
                permissionsTable.getValueAt(
                        selectedRow, 1
                ).toString()
        );

int resourceId =
        Integer.parseInt(
                permissionsTable.getValueAt(
                        selectedRow, 2
                ).toString()
        );

Permission permission = new Permission();

permission.setPermissionId(permissionId);
permission.setOperationId(operationId);
permission.setResourceId(resourceId);

EditPermissionForm editPermissionForm =
        new EditPermissionForm(
                loggedInAccount,
                permission
        );

editPermissionForm.setVisible(true);

this.dispose();
    }//GEN-LAST:event_updatePermissionButtonActionPerformed

    private void deletePermissionButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletePermissionButtonActionPerformed
        // TODO add your handling code here:
        
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "DELETE",
        "Permissions")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to delete permissions."
    );

    return;
}
        
        int selectedRow = permissionsTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a permission to delete."
    );

    return;
}

int permissionId =
        Integer.parseInt(
                permissionsTable.getValueAt(
                        selectedRow, 0
                ).toString()
        );

int confirmation =
        javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete permission "
                + permissionId + "?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {

    return;
}

PermissionDAO permissionDAO =
        new PermissionDAO();

boolean success =
        permissionDAO.deletePermission(permissionId);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Permission deleted successfully."
    );

    loadPermissions();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Permission could not be deleted. "
            + "It may be assigned to a role."
    );
}
    }//GEN-LAST:event_deletePermissionButtonActionPerformed

