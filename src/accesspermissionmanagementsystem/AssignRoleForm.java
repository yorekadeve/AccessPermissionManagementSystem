    private void assignButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignButtonActionPerformed
        // TODO add your handling code here:
                if (!permissionCheckDAO.hasPermission(
                loggedInAccount.getUserId(),
                "UPDATE",
                "Users")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Access denied. You do not have permission to assign roles."
            );

            return;
        }

        int userIndex = userComboBox.getSelectedIndex();
        int roleIndex = roleComboBox.getSelectedIndex();

        if (userIndex == -1 || roleIndex == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a user and a role."
            );

            return;
        }

        int userId = users.get(userIndex).getUserId();
        int roleId = roles.get(roleIndex).getRoleId();

        String error = userRoleDAO.assignRole(userId, roleId);

        if (error != null) {

            javax.swing.JOptionPane.showMessageDialog(this, error);

            return;
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Role assigned successfully."
        );

        loadAssignments();
    }//GEN-LAST:event_assignButtonActionPerformed

    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        // TODO add your handling code here:
                if (!permissionCheckDAO.hasPermission(
                loggedInAccount.getUserId(),
                "UPDATE",
                "Users")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Access denied. You do not have permission to remove roles."
            );

            return;
        }

        int selectedRow = assignmentsTable.getSelectedRow();

        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select an assignment to remove."
            );

            return;
        }

        int userId = Integer.parseInt(
                assignmentsTable.getValueAt(selectedRow, 0).toString()
        );

        int roleId = Integer.parseInt(
                assignmentsTable.getValueAt(selectedRow, 2).toString()
        );

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Remove this role from the user?",
                "Confirm",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        if (userRoleDAO.removeUserRole(userId, roleId)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Role removed."
            );

            loadAssignments();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Could not remove the role."
            );
        }
    }//GEN-LAST:event_removeButtonActionPerformed

