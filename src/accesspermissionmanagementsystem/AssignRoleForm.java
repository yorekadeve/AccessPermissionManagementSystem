    private void loadUsersAndRoles() {

        users = new UserDAO().getAllUsers();
        roles = new RoleDAO().getAllRoles();

        userComboBox.removeAllItems();

        for (User user : users) {
            userComboBox.addItem(
                    user.getFullName() + " (ID " + user.getUserId() + ")"
            );
        }

        roleComboBox.removeAllItems();

        for (Role role : roles) {
            roleComboBox.addItem(role.getRoleName());
        }
    }

    private void loadAssignments() {

        java.util.List<UserRole> userRoles = userRoleDAO.getAllUserRoles();

        javax.swing.table.DefaultTableModel model =
                new javax.swing.table.DefaultTableModel(
                        new Object[][]{},
                        new String[]{"User ID", "User", "Role ID", "Role"}) {

                    @Override
                    public boolean isCellEditable(int row, int column) {
                        return false;
                    }
                };

        for (UserRole userRole : userRoles) {

            model.addRow(new Object[]{
                userRole.getUserId(),
                findUserName(userRole.getUserId()),
                userRole.getRoleId(),
                findRoleName(userRole.getRoleId())
            });
        }

        assignmentsTable.setModel(model);
    }

    private String findUserName(int userId) {

        for (User user : users) {
            if (user.getUserId() == userId) {
                return user.getFullName();
            }
        }

        return "Unknown";
    }

    private String findRoleName(int roleId) {

        for (Role role : roles) {
            if (role.getRoleId() == roleId) {
                return role.getRoleName();
            }
        }

        return "Unknown";
    }

