    private void createReportButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createReportButtonActionPerformed
        // TODO add your handling code here:
        /*
     * Check permission again before generating the report.
     * This protects the operation even if the button is
     * triggered unexpectedly.
     */
    int userId = loggedInAccount.getUserId();

    boolean allowed =
            permissionCheckDAO.hasPermission(
                    userId,
                    "VIEW",
                    "Reports"
            );

    if (!allowed) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Access denied. You do not have permission to generate reports.",
                "Permission Denied",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    /*
     * Get selected dates.
     */
    java.util.Date fromDate =
            fromDateChooser.getDate();

    java.util.Date toDate =
            toDateChooser.getDate();

    /*
     * Make sure both dates were selected.
     */
    if (fromDate == null || toDate == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select both the From Date and To Date.",
                "Missing Date",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    /*
     * Make sure the date range is valid.
     */
    if (fromDate.after(toDate)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "The From Date cannot be after the To Date.",
                "Invalid Date Range",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    /*
     * Generate the report.
     */
    ReportDAO reportDAO =
            new ReportDAO();

    String report =
            reportDAO.generateReport(
                    fromDate,
                    toDate
            );

    /*
     * Display the generated report.
     */
    reportTextArea.setText(report);

    /*
     * Move the text area to the beginning.
     */
    reportTextArea.setCaretPosition(0);

    focusStatusLabel.setText(
            "Focus Status: Report generated successfully"
    );
    }//GEN-LAST:event_createReportButtonActionPerformed

    private void downloadPdfButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_downloadPdfButtonActionPerformed
        // TODO add your handling code here:
        if (loggedInAccount == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No logged-in account was found.",
                "Access Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int userId =
            loggedInAccount.getUserId();

    boolean allowed =
            permissionCheckDAO.hasPermission(
                    userId,
                    "VIEW",
                    "Reports"
            );

    if (!allowed) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Access denied. You do not have permission to download reports.",
                "Permission Denied",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String reportText =
            reportTextArea.getText();

    if (reportText == null
            || reportText.trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please generate a report first.",
                "No Report",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    javax.swing.JFileChooser fileChooser =
            new javax.swing.JFileChooser();

    fileChooser.setDialogTitle(
            "Save Access Permission System Report"
    );

    fileChooser.setSelectedFile(
            new java.io.File(
                    "Access_Permission_System_Report.pdf"
            )
    );

    int result =
            fileChooser.showSaveDialog(this);

    if (result != javax.swing.JFileChooser.APPROVE_OPTION) {

        return;
    }

    java.io.File selectedFile =
            fileChooser.getSelectedFile();

    String filePath =
            selectedFile.getAbsolutePath();

    if (!filePath.toLowerCase().endsWith(".pdf")) {

        filePath = filePath + ".pdf";
    }

    try {

        com.itextpdf.text.Document document =
                new com.itextpdf.text.Document(
                        com.itextpdf.text.PageSize.A4
                );

        com.itextpdf.text.pdf.PdfWriter.getInstance(
                document,
                new java.io.FileOutputStream(filePath)
        );

        document.open();

        com.itextpdf.text.Font titleFont =
                new com.itextpdf.text.Font(
                        com.itextpdf.text.Font.FontFamily.HELVETICA,
                        16,
                        com.itextpdf.text.Font.BOLD
                );

        com.itextpdf.text.Font normalFont =
                new com.itextpdf.text.Font(
                        com.itextpdf.text.Font.FontFamily.HELVETICA,
                        10,
                        com.itextpdf.text.Font.NORMAL
                );

        com.itextpdf.text.Paragraph title =
                new com.itextpdf.text.Paragraph(
                        "ACCESS PERMISSION SYSTEM REPORT",
                        titleFont
                );

        title.setAlignment(
                com.itextpdf.text.Element.ALIGN_CENTER
        );

        document.add(title);

        document.add(
                new com.itextpdf.text.Paragraph(
                        " "
                )
        );

        String[] lines =
                reportText.split("\\r?\\n");

        for (String line : lines) {

            document.add(
                    new com.itextpdf.text.Paragraph(
                            line,
                            normalFont
                    )
            );
        }

        document.close();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "PDF report created successfully.\n\n"
                + "Saved to:\n"
                + filePath,
                "PDF Created",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "The PDF could not be created.\n\n"
                + e.getMessage(),
                "PDF Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_downloadPdfButtonActionPerformed

