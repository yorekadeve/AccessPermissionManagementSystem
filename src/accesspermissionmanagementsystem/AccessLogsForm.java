    private void loadAccessLogs() {

    AccessLogDAO accessLogDAO = new AccessLogDAO();

    java.util.List<AccessLog> accessLogs =
            accessLogDAO.getAllAccessLogs();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) accessLogsTable.getModel();

    model.setRowCount(0);

    for (AccessLog accessLog : accessLogs) {

        model.addRow(new Object[]{
            accessLog.getLogId(),
            accessLog.getUserId(),
            accessLog.getSessionId(),
            accessLog.getOperationId(),
            accessLog.getResourceId(),
            accessLog.getTargetRecord(),
            accessLog.getActionTime(),
            accessLog.getResult()
        });
    }
}

