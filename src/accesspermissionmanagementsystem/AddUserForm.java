    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        // TODO add your handling code here:
        String fullName =
            fullNameField.getText().trim();

    String email =
            emailField.getText().trim();

    String username =
            usernameField.getText().trim();

    String password =
            new String(
                    passwordField.getPassword()
            );

    String status =
            statusComboBox
                    .getSelectedItem()
                    .toString();


    // Check required fields

    if (fullName.isEmpty()
            || email.isEmpty()
            || username.isEmpty()
            || password.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter full name, email, username and password.",
                "Missing Information",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }


    // Check password length

    if (password.length() < 6) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Password must contain at least 6 characters.",
                "Invalid Password",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }


    // Create User record

    User user =
            new User();

    user.setFullName(fullName);

    user.setEmail(email);

    user.setStatus(status);


    UserDAO userDAO =
            new UserDAO();

    int userId =
            userDAO.addUser(user);


    if (userId == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Failed to create the user.",
                "Operation Failed",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );

        return;
    }


    // Create login account

    UserAccountDAO userAccountDAO =
            new UserAccountDAO();

    boolean accountCreated =
            userAccountDAO.createAccount(
                    userId,
                    username,
                    password,
                    status.equalsIgnoreCase("ACTIVE")
                            ? "ACTIVE"
                            : "DISABLED"
            );


    if (accountCreated) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "User and login account created successfully."
        );

        UsersForm usersForm =
                new UsersForm(
                        loggedInAccount
                );

        usersForm.setVisible(true);

        this.dispose();

    } else {

        /*
         * The User record was created,
         * but the login account failed.
         *
         * Remove the User record so we
         * do not leave an incomplete user.
         */

        userDAO.deleteUser(userId);

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "The user was created, but the login account "
                + "could not be created.\n"
                + "The user record has been rolled back.",
                "Account Creation Failed",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_saveButtonActionPerformed

