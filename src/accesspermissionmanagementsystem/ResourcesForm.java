    private void updateResourceButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateResourceButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "UPDATE",
        "Resources")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to update resources."
    );

    return;
}

int selectedRow = resourcesTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a resource to update."
    );

    return;
}

int resourceId =
        Integer.parseInt(
                resourcesTable.getValueAt(selectedRow, 0).toString()
        );

String resourceName =
        resourcesTable.getValueAt(selectedRow, 1).toString();

String description =
        resourcesTable.getValueAt(selectedRow, 2).toString();

EditResourceForm editResourceForm =
        new EditResourceForm(
                loggedInAccount,
                resourceId,
                resourceName,
                description
        );

editResourceForm.setVisible(true);

this.dispose();
    }//GEN-LAST:event_updateResourceButtonActionPerformed

    private void deleteResourceButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteResourceButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "DELETE",
        "Resources")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to delete resources."
    );

    return;
}

int selectedRow = resourcesTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a resource to delete."
    );

    return;
}

int resourceId =
        Integer.parseInt(
                resourcesTable.getValueAt(selectedRow, 0).toString()
        );

String resourceName =
        resourcesTable.getValueAt(selectedRow, 1).toString();

int confirmation =
        javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete "
                + resourceName + "?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {

    return;
}

ResourceDAO resourceDAO = new ResourceDAO();

boolean success =
        resourceDAO.deleteResource(resourceId);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Resource deleted successfully."
    );

    loadResources();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "The resource could not be deleted.\n\n"
            + "It may be referenced by one or more permissions.",
            "Delete Failed",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_deleteResourceButtonActionPerformed

