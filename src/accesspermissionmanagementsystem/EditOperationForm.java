    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        // TODO add your handling code here:
        String operationName =
        operationNameField.getText().trim();

String description =
        descriptionField.getText().trim();

if (operationName.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter an operation name."
    );

    return;
}

Operation operation =
        new Operation();

operation.setOperationId(operationId);
operation.setOperationName(operationName);
operation.setDescription(description);

OperationDAO operationDAO =
        new OperationDAO();

boolean success =
        operationDAO.updateOperation(operation);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Operation updated successfully."
    );

    OperationsForm operationsForm =
            new OperationsForm(loggedInAccount);

    operationsForm.setVisible(true);

    this.dispose();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Operation could not be updated."
    );
}
    }//GEN-LAST:event_saveButtonActionPerformed

