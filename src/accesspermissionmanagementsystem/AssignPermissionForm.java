    private void assignButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignButtonActionPerformed
        // TODO add your handling code here:
                if (!permissionCheckDAO.hasPermission(
                loggedInAccount.getUserId(),
                "UPDATE",
                "Roles")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Access denied. You do not have permission to assign permissions."
            );

            return;
        }

        int roleIndex = roleComboBox.getSelectedIndex();
        int permissionIndex = permissionComboBox.getSelectedIndex();

        if (roleIndex == -1 || permissionIndex == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a role and a permission."
            );

            return;
        }

        int roleId = roles.get(roleIndex).getRoleId();
        int permissionId =
                permissions.get(permissionIndex).getPermissionId();

        String error =
                rolePermissionDAO.assignPermission(roleId, permissionId);

        if (error != null) {

            javax.swing.JOptionPane.showMessageDialog(this, error);

            return;
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Permission assigned successfully."
        );

        loadAssignments();
    }//GEN-LAST:event_assignButtonActionPerformed

    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        // TODO add your handling code here:
                if (!permissionCheckDAO.hasPermission(
                loggedInAccount.getUserId(),
                "UPDATE",
                "Roles")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Access denied. You do not have permission to remove permissions."
            );

            return;
        }

        int selectedRow = rolePermissionsTable.getSelectedRow();

        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select an assignment to remove."
            );

            return;
        }

        int roleId = Integer.parseInt(
                rolePermissionsTable.getValueAt(selectedRow, 0).toString()
        );

        int permissionId = Integer.parseInt(
                rolePermissionsTable.getValueAt(selectedRow, 2).toString()
        );

        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Remove this permission from the role?",
                "Confirm",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        if (rolePermissionDAO.removeRolePermission(roleId, permissionId)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Permission removed."
            );

            loadAssignments();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Could not remove the permission."
            );
        }
    }//GEN-LAST:event_removeButtonActionPerformed

