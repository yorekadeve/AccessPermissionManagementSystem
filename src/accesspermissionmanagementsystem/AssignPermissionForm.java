    private void loadData() {

        roles = new RoleDAO().getAllRoles();
        permissions = new PermissionDAO().getAllPermissions();
        operations = new OperationDAO().getAllOperations();
        resources = new ResourceDAO().getAllResources();

        roleComboBox.removeAllItems();

        for (Role role : roles) {
            roleComboBox.addItem(role.getRoleName());
        }

        permissionComboBox.removeAllItems();

        for (Permission permission : permissions) {
            permissionComboBox.addItem(
                    findPermissionLabel(permission.getPermissionId())
            );
        }
    }

    private void loadAssignments() {

        java.util.List<RolePermission> rolePermissions =
                rolePermissionDAO.getAllRolePermissions();

        javax.swing.table.DefaultTableModel model =
                new javax.swing.table.DefaultTableModel(
                        new Object[][]{},
                        new String[]{"Role ID", "Role",
                            "Permission ID", "Permission"}) {

                    @Override
                    public boolean isCellEditable(int row, int column) {
                        return false;
                    }
                };

        for (RolePermission rolePermission : rolePermissions) {

            model.addRow(new Object[]{
                rolePermission.getRoleId(),
                findRoleName(rolePermission.getRoleId()),
                rolePermission.getPermissionId(),
                findPermissionLabel(rolePermission.getPermissionId())
            });
        }

        rolePermissionsTable.setModel(model);
    }

    private String findRoleName(int roleId) {

        for (Role role : roles) {
            if (role.getRoleId() == roleId) {
                return role.getRoleName();
            }
        }

        return "Unknown";
    }

    private String findPermissionLabel(int permissionId) {

        for (Permission permission : permissions) {

            if (permission.getPermissionId() == permissionId) {

                String operationName = "Unknown";
                String resourceName = "Unknown";

                for (Operation operation : operations) {
                    if (operation.getOperationId()
                            == permission.getOperationId()) {
                        operationName = operation.getOperationName();
                    }
                }

                for (Resource resource : resources) {
                    if (resource.getResourceId()
                            == permission.getResourceId()) {
                        resourceName = resource.getResourceName();
                    }
                }

                return operationName + " on " + resourceName;
            }
        }

        return "Unknown";
    }

