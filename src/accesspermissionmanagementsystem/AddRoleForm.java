    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        // TODO add your handling code here:
        String roleName = roleNameField.getText().trim();
String description = descriptionField.getText().trim();

if (roleName.isEmpty() || description.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter role name and description."
    );

    return;
}

Role role = new Role();

role.setRoleName(roleName);
role.setDescription(description);

RoleDAO roleDAO = new RoleDAO();

boolean success = roleDAO.addRole(role);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Role added successfully."
    );

    RolesForm rolesForm =
            new RolesForm(loggedInAccount);

    rolesForm.setVisible(true);

    this.dispose();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to add role."
    );
}
    }//GEN-LAST:event_saveButtonActionPerformed

