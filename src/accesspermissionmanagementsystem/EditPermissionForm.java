    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        // TODO add your handling code here:
        String operationText =
        operationIdField.getText().trim();

String resourceText =
        resourceIdField.getText().trim();

String description =
        descriptionField.getText().trim();

if (operationText.isEmpty()
        || resourceText.isEmpty()
        || description.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please enter operation ID, resource ID, and description."
    );

    return;
}

int operationId;
int resourceId;

try {

    operationId = Integer.parseInt(operationText);
    resourceId = Integer.parseInt(resourceText);

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Operation ID and Resource ID must be numbers."
    );

    return;
}

permission.setOperationId(operationId);
permission.setResourceId(resourceId);
permission.setDescription(description);

PermissionDAO permissionDAO =
        new PermissionDAO();

boolean success =
        permissionDAO.updatePermission(permission);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Permission updated successfully."
    );

    PermissionsForm permissionsForm =
            new PermissionsForm(loggedInAccount);

    permissionsForm.setVisible(true);

    this.dispose();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to update permission."
    );
}
    }//GEN-LAST:event_saveButtonActionPerformed

