    private void closeSessionButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_closeSessionButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "UPDATE",
        "Sessions")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to close sessions."
    );

    return;
}

int selectedRow = sessionsTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a session to close."
    );

    return;
}

int sessionId =
        Integer.parseInt(
                sessionsTable.getValueAt(selectedRow, 0).toString()
        );

String status =
        sessionsTable.getValueAt(selectedRow, 4).toString();

if ("CLOSED".equals(status)) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "This session is already closed."
    );

    return;
}

int confirmation =
        javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to close this session?",
                "Confirm Close Session",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {

    return;
}

SessionDAO sessionDAO = new SessionDAO();

boolean success =
        sessionDAO.closeSession(sessionId);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Session closed successfully."
    );

    loadSessions();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "The session could not be closed.",
            "Operation Failed",
            javax.swing.JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_closeSessionButtonActionPerformed

