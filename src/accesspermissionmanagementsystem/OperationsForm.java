    private void addOperationButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addOperationButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "CREATE",
        "Operations")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to create operations."
    );

    return;
}

AddOperationForm addOperationForm =
        new AddOperationForm(loggedInAccount);

addOperationForm.setVisible(true);

this.dispose();
    }//GEN-LAST:event_addOperationButtonActionPerformed

    private void updateOperationButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateOperationButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "UPDATE",
        "Operations")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to update operations."
    );

    return;
}

int selectedRow =
        operationsTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an operation to update."
    );

    return;
}

int operationId =
        Integer.parseInt(
                operationsTable
                        .getValueAt(selectedRow, 0)
                        .toString()
        );

String operationName =
        operationsTable
                .getValueAt(selectedRow, 1)
                .toString();

String description =
        operationsTable
                .getValueAt(selectedRow, 2)
                .toString();

EditOperationForm editOperationForm =
        new EditOperationForm(
                loggedInAccount,
                operationId,
                operationName,
                description
        );

editOperationForm.setVisible(true);

this.dispose();
    }//GEN-LAST:event_updateOperationButtonActionPerformed

    private void deleteOperationButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteOperationButtonActionPerformed
        // TODO add your handling code here:
        if (!permissionCheckDAO.hasPermission(
        loggedInAccount.getUserId(),
        "DELETE",
        "Operations")) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Access denied. You do not have permission to delete operations."
    );

    return;
}

int selectedRow =
        operationsTable.getSelectedRow();

if (selectedRow == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select an operation to delete."
    );

    return;
}

int operationId =
        Integer.parseInt(
                operationsTable
                        .getValueAt(selectedRow, 0)
                        .toString()
        );

String operationName =
        operationsTable
                .getValueAt(selectedRow, 1)
                .toString();

int confirmation =
        javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete "
                + operationName + "?",
                "Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION
        );

if (confirmation != javax.swing.JOptionPane.YES_OPTION) {

    return;
}

OperationDAO operationDAO =
        new OperationDAO();

boolean success =
        operationDAO.deleteOperation(operationId);

if (success) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Operation deleted successfully."
    );

    loadOperations();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "The operation could not be deleted.\n\n"
            + "It may be referenced by one or more permissions.",
            "Delete Failed",
            javax.swing.JOptionPane.WARNING_MESSAGE
    );
}
    }//GEN-LAST:event_deleteOperationButtonActionPerformed

